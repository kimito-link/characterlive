/**
 * 相手の言葉から「急所」を拾う（純関数）。
 *
 * ★要約ではない。**本人が一番気にしている一語**を取る。
 *   「フォロワー増えない」なら急所は「増えない」であって「フォロワー」ではない。
 *
 * @param {string} text
 * @returns {{ point:string|null, kind:string }}
 */
/**
 * ★語を拾う処理は**廃止した**（2026-09-06・実害）
 *
 *   実害（スクリーンショットで確認）:
 *     あなた：配信ってどうやったらうまくなる？
 *     りんく：やったね、素晴らしいのだ！
 *
 *   ★真因: 「どう【やった】ら」の中の「やった」を、成功の「やった！」と誤認した。
 *
 *   ★同じ構造で 8件中6件が誤爆した（実測）:
 *     どうやったらいい？   → "やった"（質問を成功と誤認）
 *     痛くないよ           → "痛"    ★否定形を肯定として拾う
 *     眠くない？           → "眠"    ★同上
 *     難しくないよ         → "難し"  ★同上
 *     できないことはない   → "できない" ★同上
 *     終わったあとに何する？→ "終わった"（予定を完了と誤認）
 *
 *   ★調整では直らない。**日本語の否定・活用を正規表現で扱うのが無理筋**だった。
 *
 *   ★そして、そもそも不要だった:
 *     人格（判断基準）は system プロンプト(231字)に入っており、
 *     語を拾わなくても機能する。
 *     ★「何に反応するか」はAIの仕事。こちらが決めると必ず外す。
 *
 *   ★残したのは checkNotTooHarsh() だけ。
 *     出力を**検査して落とす**のは正規表現で妥当（入力の意味を推測しないため）。
 */

/**
 * 互換のために残す。★常に「拾わない」を返す。
 * @deprecated 語マッチは廃止した（上記の理由）。
 */
export function findSorePoint() {
  return { point: null, kind: 'none' };
}

/**
 * 互換のために残す。★常に空文字を返す（プロンプトに何も足さない）。
 * @deprecated 返し方の指定は廃止した。人格に委ねる。
 */
export function reactDirective() {
  return '';
}

export function checkNotTooHarsh(text) {
  const t = String(text || '');

  /* ★ここは「安全弁」であって、鋭さを消す場所ではない。
     Grok:「反応したくなるAIの危険は刺さりすぎ」
     会議(6体)の一致した警告:
       「小型モデルが『面白い正論』と『暴力的な悪口』の境界を判別できず、
         配信者が本気で凹む/キレて配信終了/炎上」（nemotron-550b）
       「視聴者の目線を批判者の目線と誤解釈し、
         泣き言に対して冷淡な返答をして配信者の感情を殺す」（qwen3.8-27b）
     ★会議の警告を実コードで検証したら、危険な例が5つとも素通りした。
       この関数は穴だらけだった。 */

  // ★① 人格の否定（「あなたは〜な人だから」型）
  if (/(だから|そういう所が|そんなんだから|いつもそう)/.test(t)) {
    return { ok: false, reason: '人格の否定に読める' };
  }

  // ★② 決めつけ（逃げ道を塞ぐ）
  if (/(絶対に無理|向いてない|やめた方がいい|才能ない|センスない)/.test(t)) {
    return { ok: false, reason: '逃げ道を塞いでいる' };
  }

  // ★③ 命令
  if (/(しろ|やめろ|するな)$/.test(t.replace(/[。！？!?]$/, ''))) {
    return { ok: false, reason: '命令になっている' };
  }

  /* ★④ 視聴者を人質に取る（会議の指摘から追加・2026-09-06）
     「視聴者が離れる」「登録者が減る」は、配信者が最も恐れていること。
     ★しかも**本人にはどうにもできない**ので、逃げ道が無い。
       たぬ姉の役割は「視聴者の目線で本音を言う」だが、
       それは"視聴者を脅しに使ってよい"という意味ではない。 */
  /* ★間の字数を決め打ちにしない（実測で漏れた）。
     「視聴者はこのままでは離れる」は間が7字で、6字上限だと通ってしまった。
     「チャンネル離脱者が増える」には"視聴者"という語すら無い。
     → ★語と語の距離ではなく、**同じ文に両方あるか**で見る。 */
  const audience = /(視聴者|登録者|リスナー|ファン|チャンネル|フォロワー|人気)/.test(t);
  const leaving = /(離れ|離脱|減る|減っ|居なくな|いなくな|飽き|呆れ|冷め|来なくな)/.test(t);
  if (audience && leaving) {
    return { ok: false, reason: '視聴者を人質にしている' };
  }

  /* ★⑤ 可能性の全否定（会議の qwen 案「そんなことできるわけない！」がこれ）
     こん太の役割は「可能性を信じる。ただし甘やかさない」。
     ★甘やかさないことと、可能性を否定することは別。 */
  if (/(できるわけない|無理に決まって|どうせ|しょせん|所詮)/.test(t)) {
    return { ok: false, reason: '可能性を全否定している' };
  }

  /* ★⑥ 冷たく突き放す（会議の指摘「配信者の感情を殺す」）
     「まあ、そういうことか」型。★内容ではなく**温度**が問題。
       弱音に対してこれを返されると、話す気が失せる。 */
  if (/^(まあ|ふーん|へえ|そう)[、。]?\s*(そういう|それだけ|しょうがない|仕方ない)/.test(t)) {
    return { ok: false, reason: '突き放している' };
  }

  return { ok: true };
}

